  /** 是否应显示更新日志（版本比上次已显示的新） */
  function shouldShow () {
    try {
      return localStorage.getItem(STORAGE_KEY) !== CONFIG.version
    } catch (_) {
      return true
    }
  }

  /** 标记当前版本已显示 */
  function markSeen () {
    try { localStorage.setItem(STORAGE_KEY, CONFIG.version) } catch (_) {}
  }

  /** 显示更新日志弹窗（累积显示所有历史版本） */
  function show () {
    if (!LOGS.length) { markSeen(); return }

    const renderVersion = (log, isNewest) => `
      <div class="changelog-version ${isNewest ? 'is-newest' : ''}">
        <header class="changelog-hero">
          <div class="changelog-meta">
            <span>${isNewest ? '最新版本' : '历史版本'}</span>
            <small>VERSION ${log.version}</small>
            <time>${log.date}</time>
          </div>
          <h3>${log.title}</h3>
          ${isNewest ? '<p>妖林又发生了一些变化，以下是本次冒险内容。</p>' : ''}
        </header>
        <div class="changelog-list">
          ${log.sections.map(s => `
            <section class="changelog-section">
              <div class="changelog-section-title"><i>${s.icon}</i><b>${s.title}</b></div>
              <ul>${s.items.map(i => `<li>${i}</li>`).join('')}</ul>
            </section>`).join('')}
        </div>
      </div>`

    const newest = LOGS[0]
    const history = LOGS.slice(1).map(l => renderVersion(l, false)).join('')

    Dialog.show({
      title: `✨ 更新日志`,
      className: 'changelog-modal',
      body: `
        ${renderVersion(newest, true)}
        ${history ? `<details class="changelog-history"><summary><span>📜 历史更新</span><small>展开查看以前的版本</small></summary>${history}</details>` : ''}
        <footer class="changelog-footer">
          <b>✦ 感谢游玩《妖林绮梦》</b>
          <small>🍻 妓女打工玩法参考：<a href="https://sissy.game/1197.html" target="_blank" rel="noopener">sissy.game/1197.html</a></small>
        </footer>
      `,
      actions: [
        { label: '知道了', cls: 'btn-primary', handler: () => { Dialog.close(); markSeen() } },
      ],
    })
  }

  /** 启动时检查并显示（应在进入游戏界面后调用） */
  function check () {
    if (shouldShow()) show()
  }

  return { check, show, shouldShow, markSeen }
